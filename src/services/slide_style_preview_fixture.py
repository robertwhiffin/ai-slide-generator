from src.domain.deck_spec import ResolvedData, SlideSpec

# --- Version markers ---------------------------------------------------------
# Bump the specific marker whose behaviour changed; bump PREVIEW_GENERATION_VERSION
# to force-invalidate ALL previews after a cross-cutting release. Every marker is
# folded into the fingerprint below.
PREVIEW_BRIEF_VERSION = "2"        # bumped: the brief is now the slide specs below
PREVIEW_PROMPT_VERSION = "2"       # bumped: the builder payload replaces a chat prompt
PREVIEW_GENERATOR_VERSION = "3"    # bumped: generated by the graph builder role
PREVIEW_RENDERER_VERSION = "1"     # the frontend render contract (buildSlideDocument use)
PREVIEW_GENERATION_VERSION = "1"   # umbrella: bump to invalidate every preview

# The graph role that authors preview slides. Real graph decks build every slide
# with it, so a preview made with it shows what that style's real slides get.
PREVIEW_AGENT_KEY = "builder"

# Number of slides a preview may hold. Each spec below yields one slide, so a
# count outside this inclusive range means the generator itself went wrong; the
# output validator rejects it rather than caching a broken preview.
PREVIEW_MIN_SLIDES = 2
PREVIEW_MAX_SLIDES = 4

