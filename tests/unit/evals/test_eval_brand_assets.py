class _ScriptedChat:
    """A chat-model double behind the real ``DatabricksModelAdapter``: records its binding and the
    conversation of each round, then answers from a script."""

    def __init__(self, script):
        self.script = list(script)
        self.bindings: list[tuple[list, dict]] = []
        self.raw_inputs: list[Any] = []

    def bind_tools(self, tools, **kwargs):
        tools = list(tools)
        self.bindings.append((tools, kwargs))
        schema = next(t for t in tools if isinstance(t, type))

        def reply(model_input):
            self.raw_inputs.append(list(model_input) if isinstance(model_input, list) else model_input)
            if not self.script:
                raise AssertionError("the model was called more often than scripted")
            return self.script.pop(0)(schema)

        return replying(reply)


