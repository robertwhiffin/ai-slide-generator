def _run_tool(tool, args: dict) -> str:
    """Run one toolset tool the way the runtime's loop does: parsed args, a time budget."""
    return tool.run(tool.args_schema.model_validate(args), remaining_seconds=300.0)


class _CapturingAdapter:
    """The runtime's model seam: records the tools each call is handed and, when scripted, calls
    the search the way the runtime's loop does before answering.

    A run with the search reaches ``invoke_with_tools`` (the harness hands the toolset to the tool
    loop, RA19); a run without it reaches ``invoke`` and records ``()``."""

    def __init__(self, *, searches=(), html: str | None = GOOD_HTML):
        self.searches = [dict(a) for a in searches]
        self.html = html
        self.tools_seen: list[tuple] = []
        self.results: list[dict] = []
        self._lock = threading.Lock()

    def invoke(self, *, agent_key, configuration, schema, prompt):
        with self._lock:
            self.tools_seen.append(())
        return self._answer(agent_key, schema)

    def invoke_with_tools(self, *, agent_key, configuration, schema, prompt, toolset):
        tools = tuple(toolset.tools)
        with self._lock:
            self.tools_seen.append(tools)
        by_name = {tool.name: tool for tool in tools}
        for args in self.searches:
            self.results.append(_unwrap(_run_tool(by_name[SEARCH], args)))
        return self._answer(agent_key, schema)

    def _answer(self, agent_key, schema):
        out = fake_output(agent_key)
        if agent_key in ("builder", "fixer") and self.html is not None:
            out["html"] = self.html
        return schema.model_validate(out)


def _run(agent_key: str, payload: dict, adapter, *, design_system_active: bool = True):
    runner = Runner(model_adapter=adapter, max_infra_retries=0)
    return runner.run(config.v1_baseline(agent_key), payload,
                      design_system_active=design_system_active)


def _row(handle: str) -> dict:
    asset = next(r for r in INDEX if r["handle"] == handle)
    asset_id = int(DS_ASSET_PLACEHOLDER_PATTERN.fullmatch(handle).group(1))
    return {
        "id": asset_id, "kind": asset["kind"], "filename": asset["filename"],
        "usage": '<img src="{{ds-asset:%d}}" alt="%s"/>' % (
            asset_id, html_mod.escape(asset["filename"])),
    }


_KIND_RANK = ("logo", "lockup", "icon", "illustration", "background")


def _searched(*, query=None, kind=None) -> list[str]:
    """What ``design_system_service.search_assets`` returns over the index, as handles."""
    rows = list(INDEX)
    if kind:
        rows = [r for r in rows if r["kind"].lower() == kind.strip().lower()]
    if query:
        rows = [r for r in rows if query.strip().lower() in r["filename"].lower()]

    def key(r):
        rank = _KIND_RANK.index(r["kind"]) if r["kind"] in _KIND_RANK else len(_KIND_RANK)
        return (rank, r["filename"], int(DS_ASSET_PLACEHOLDER_PATTERN.fullmatch(r["handle"]).group(1)))

    return [r["handle"] for r in sorted(rows, key=key)]


