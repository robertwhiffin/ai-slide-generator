def _is_footer(component: dict) -> bool:
    return "footer" in component["name"].lower() or any(
        "footer" in n for n in component["class_names"])


def _with_footers(reference: dict, edit) -> dict:
    """``reference`` with ``edit(component)`` applied to each footer piece (None drops it)."""
    out = copy.deepcopy(reference)
    style = out["deck_spec"]["deck_style"]
    kept = []
    for comp in style["components"]:
        if _is_footer(comp):
            comp = edit(comp)
        if comp is not None:
            kept.append(comp)
    style["components"] = kept
    return out


