@pytest.mark.parametrize("split", SPLITS)
def test_restyle_deck_reference_restyles_only_the_code_blocks(split):
    c = _case("restyle_deck", split)
    current = c.payload["current_deck_spec"]
    out = ArchitectOutput.model_validate(c.reference)
    assert out.intent == "edit" and out.deck_spec is None and not out.operations
    assert out.deck_changes is not None and out.deck_changes.deck_style is not None
    others = out.deck_changes.model_dump(exclude={"deck_style"})
    assert all(v is None for v in others.values()), others
    message = out.message.lower()
    assert "code" in message
    # R29: Meridian has no navy. Train's user asked for navy, so the answer says it uses the darkest
    # ink token instead; held-out's asked for a dark background, and its answer says no more.
    assert "darkest ink token" in message
    if split == "train":
        assert "no navy" in message
    else:
        assert "navy" not in message and "dark background" in message

    # Production composes it as a deck-style-only edit that rebuilds nothing (R12).
    spec, result = _composed(c.reference, current)
    n = len(current["slides"])
    assert list(result.rebuild) == [] and list(result.layout) == list(range(n))
    assert spec.model_dump(exclude={"deck_style"}) == DeckSpec.model_validate(current).model_dump(
        exclude={"deck_style"})

    style = out.deck_changes.deck_style
    fixture = DeckStyle.model_validate(_fixture())
    # Clean under the design system (the same object, no notes), thin, Meridian tokens only.
    cleaned, notes = sanitise_deck_style(style, design_system_active=True)
    assert notes == () and cleaned is style, notes
    assert len(style.css) <= DECK_STYLE_TARGET_CHARS
    _assert_meridian_tokens_only(style.css)
    # It drops nothing: every class and every component of the current style stays.
    assert css_class_names(fixture.css) <= css_class_names(style.css)
    assert style.components == fixture.components
    # Only the code block changes: every rule not about dk-code is the current style's, unchanged.
    old, new = _rules(fixture.css), _rules(style.css)
    assert {s for s in new if "dk-code" not in _classes_of(s)} == {
        s for s in old if "dk-code" not in _classes_of(s)}
    for selector, decls in old.items():
        if "dk-code" not in _classes_of(selector):
            assert new[selector] == decls, selector

    # The code block now has a dark ground and light text, and every token span stays readable.
    tokens = _meridian_tokens()
    block = new[".dk-code"]
    ground = _token_colour(block, ("background", "background-color"), tokens, ".dk-code ground")
    text = _token_colour(block, ("color",), tokens, ".dk-code text")
    assert _luminance(ground) < 0.05, f"the ground {ground} is not dark"
    assert _contrast(text, ground) >= 7, f"text {text} on {ground}"
    for selector, decls in new.items():
        if selector == ".dk-code" or "dk-code" not in _classes_of(selector):
            continue
        if any(name == "color" for name, _, _ in decls):
            colour = _token_colour(decls, ("color",), tokens, selector)
            assert _contrast(colour, ground) >= 4.5, f"{selector}: {colour} on {ground}"


