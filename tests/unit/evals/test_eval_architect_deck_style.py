def _fixture() -> dict:
    return json.loads(FIXTURE.read_text())


def _case(cid: str, split: str = "train") -> Case:
    return case.load_case(AGENT, cid, **case.split_kwargs(split))


def _should_fail(cid: str, split: str = "train") -> dict:
    cal = judge_mod.load_calibration(AGENT, cid, **case.split_kwargs(split))
    assert cal is not None, f"no calibration.json for {split}/{cid}"
    return cal["should_fail"]


def _case_digest(split: str, cid: str) -> str:
    d = case.cases_dir(AGENT, split=split) / cid
    h = hashlib.sha256()
    for name in FILES:
        h.update(name.encode() + b"\0" + (d / name).read_bytes() + b"\0")
    return h.hexdigest()


def _styled_deck(split: str = "train") -> dict:
    """The split's gold deck as a deck-style build leaves it: the fixture style, a look per slide."""
    spec = copy.deepcopy(case.gold_deck_spec(split))
    for slide in spec["slides"]:
        slide["look"] = LOOK
    spec["deck_style"] = _fixture()
    DeckSpec.model_validate(spec)
    return spec


def _content(slide: dict) -> dict:
    return SlideContent.from_slide_spec(SlideSpec.model_validate(slide)).model_dump(mode="json")


def _answer(operations=None, *, deck_changes=None, intent="edit", message="I'll restyle the code.",
            targets=(), deck_spec=None) -> dict:
    """An architect answer in the runner's form (``ArchitectOutput.model_dump``)."""
    out = {
        "intent": intent, "message": message, "deck_spec": deck_spec, "data_request": None,
        "target_positions": list(targets), "proposed_design_contract": None,
        "operations": operations, "deck_changes": deck_changes,
    }
    return ArchitectOutput.model_validate(out).model_dump(mode="json")


def _build(spec: dict) -> dict:
    return _answer(intent="build", message="Here is the deck.", deck_spec=spec)


def _code_block(css: str, replacements: dict[str, str]) -> str:
    """``css`` with declarations swapped inside its top-level ``.dk-code {`` rule only."""
    start = css.index("\n.dk-code {") + 1
    end = css.index("}", start) + 1
    block = css[start:end]
    for old, new in replacements.items():
        assert block.count(old) == 1, old
        block = block.replace(old, new)
    return css[:start] + block + css[end:]


