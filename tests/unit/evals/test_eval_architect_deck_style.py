#: The real scorer's signature, read once: a second spy must not bind against the first.
_DECK_STYLE_SCORE_SIGNATURE = inspect.signature(scorers._deck_style_score)


def _spy_deck_style_score(monkeypatch, verdict):
    calls = []

    def spy(*args, **kwargs):
        calls.append(dict(_DECK_STYLE_SCORE_SIGNATURE.bind(*args, **kwargs).arguments))
        return verdict

    monkeypatch.setattr(scorers, "_deck_style_score", spy)
    return calls


def test_architect_build_scoring_routes_through_the_deck_style_score(monkeypatch):
    answer = _build(_styled_deck())
    calls = _spy_deck_style_score(monkeypatch, (False, "Deck style: SPY-7B"))
    got = expected_category_score(AGENT, answer, BUILD_EXPECT, design_system_active=True)
    assert got == (False, "Deck style: SPY-7B")
    assert calls == [{"structured": answer, "expect": BUILD_EXPECT, "design_system_active": True}]

    # A passing deck style leaves the build's own pass rationale.
    calls = _spy_deck_style_score(monkeypatch, (True, "Deck style: SPY-7B ok"))
    assert expected_category_score(AGENT, answer, BUILD_EXPECT, design_system_active=False) == (
        True, "Architect intent and positions match")
    assert [c["design_system_active"] for c in calls] == [False]

