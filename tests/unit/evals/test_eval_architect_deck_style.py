def _meridian_tokens() -> dict[str, str]:
    """Meridian's colour tokens: ``--name`` -> ``#RRGGBB``."""
    return dict(re.findall(r"(--[\w-]+)\s*:\s*(#[0-9A-Fa-f]{6})\b", case.meridian_section_css()))


def _luminance(hex_colour: str) -> float:
    def channel(c: int) -> float:
        s = c / 255
        return s / 12.92 if s <= 0.03928 else ((s + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_colour[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def _contrast(a: str, b: str) -> float:
    hi, lo = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def _token_colour(decls: tuple, names: tuple[str, ...], tokens: dict[str, str], where: str) -> str:
    """The last of ``names`` declared in ``decls``, which must be one Meridian ``var()`` token."""
    values = [value for name, value, _ in decls if name in names]
    assert values, f"{where}: no {' / '.join(names)} declaration"
    found = re.fullmatch(r"var\(\s*(--[\w-]+)\s*\)", values[-1])
    assert found, f"{where}: {values[-1]!r} is not a single Meridian token"
    assert found.group(1) in tokens, f"{where}: {found.group(1)} is not a Meridian colour token"
    return tokens[found.group(1)]


def _assert_meridian_tokens_only(css: str) -> None:
    """The deck style paints with Meridian tokens only: no hex, no rgb()/hsl(), no token Meridian
    does not define."""
    section_css = case.meridian_section_css()
    used = set(re.findall(r"var\(\s*(--[\w-]+)", css))
    undefined = sorted(t for t in used if not re.search(rf"{re.escape(t)}\s*:", section_css))
    assert not undefined, f"tokens Meridian does not define: {undefined}"
    assert not re.search(r"#[0-9a-fA-F]{3,8}\b", css), "a hex colour literal"
    assert not re.search(r"\b(rgba?|hsla?)\(", css, re.I), "an rgb()/hsl() colour"


