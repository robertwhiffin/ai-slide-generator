"""Prompt contract: the builder fills a bound template section and keeps its treatment.

Task 6 of the design-system slide-type binding.  Spec:
docs/superpowers/specs/2026-10-13-architect-slide-type-design.md ("Builder behaviour").

These pin phrases, not exact wording: each check is a regex over the whitespace-,
case- and backtick-normalised prompt (the pattern from test_architect_edit_prompt.py,
Task 5), so the implementer may reword freely as long as the instruction is present.

Only the prompt is pinned here.  The frozen v1 manifest is regenerated by
``python -m evals.harness.promote`` (PLAN-CORRECTIONS C6); the last test pins that the
promoted manifest carries exactly the skill's INSTRUCTIONS.
"""

from __future__ import annotations

import re

import pytest

import src.core.database  # noqa: F401  (must be imported before other src.* modules)
from src.core.skills.builder import INSTRUCTIONS
from src.services.graph_definition_manifest import load_graph_v1_manifest


def _plain(text: str) -> str:
    """Whitespace-collapsed, lower-cased text with markdown backticks removed."""
    return re.sub(r"\s+", " ", text.replace("`", "")).strip().lower()


PLAIN = _plain(INSTRUCTIONS)


def _block(heading: str) -> str:
    blocks = [b for b in INSTRUCTIONS.split("\n\n") if b.startswith(heading)]
    assert len(blocks) == 1, f"expected exactly one {heading!r} block, found {len(blocks)}"
    return _plain(blocks[0])


def _window(anchor: str, before: int = 0, after: int = 300) -> str:
    """Plain text around the first occurrence of ``anchor`` (fails if absent)."""
    i = PLAIN.find(anchor)
    assert i != -1, f"prompt never mentions {anchor!r}"
    return PLAIN[max(0, i - before) : i + after]


# --- INPUT names the four binding keys ---------------------------------------


@pytest.mark.parametrize(
    "key",
    ("section_html", "section_css", "slide_spec.slide_type", "template_section_index"),
)
def test_input_block_names_the_binding_key(key):
    assert key in _block("INPUT"), f"INPUT block does not name {key!r}"


# --- Non-empty section_html: fill the bound structure ------------------------

NON_EMPTY_CONDITION = (
    r"(section_html (is |was )?(non-empty|not empty|provided|supplied|present|set)"
    r"|(non-empty|not empty|provided|supplied) section_html)"
)

# Each entry: (description, regex over the plain prompt).  Numeric gaps are generous
# but bounded so a rule has to sit near its subject, not merely somewhere in the prompt.
NON_EMPTY_RULES = (
    ("condition: section_html non-empty", NON_EMPTY_CONDITION),
    (
        "fill that structure",
        NON_EMPTY_CONDITION + r".{0,400}fill (in )?(that|the|this|its)[^.]{0,40}"
        r"(structure|section|markup|html)",
    ),
    (
        "keep the outer root tag, and say a <section> root is allowed",
        r"keep (the |its )?(same |original )?(outer |root )(root|tag|element)[^.]{0,200}"
        r"<?section>?|"
        r"(outer root|root tag|root element)[^.]{0,200}<?section>?[^.]{0,80}"
        r"(allowed|fine|ok|permitted|valid)",
    ),
    (
        "keep the class tokens that carry background",
        r"keep[^.]{0,120}class tokens?[^.]{0,120}(background|paint|fill|ground)|"
        r"keep[^.]{0,60}(background|paint|fill|ground)[^.]{0,80}class tokens?",
    ),
    (
        "no inline color: / background:",
        r"(do not|don't|never|no)[^.]{0,40}inline color:?[^.]{0,30}background",
    ),
    (
        "follow the bound section even when content_brief names a different kind",
        r"content_brief[^.]{0,160}(different|another|other|differs|conflict|mismatch)"
        r"[^.]{0,200}(bound|section_html|selected)|"
        r"(even if|although|regardless|whether|if)[^.]{0,80}content_brief"
        r"[^.]{0,200}(different|another|other)[^.]{0,200}"
        r"(fill|follow|use|build)[^.]{0,60}(bound|section_html|selected)",
    ),
)


@pytest.mark.parametrize(
    ("description", "pattern"), NON_EMPTY_RULES, ids=[d for d, _ in NON_EMPTY_RULES]
)
def test_prompt_states_non_empty_section_html_rule(description, pattern):
    assert re.search(pattern, PLAIN), f"builder prompt lacks: {description}"


def test_same_element_rule_names_dark_white_event_and_the_painting_element():
    # "dark" / "white" / "event" live on the element that paints the fill, not a wrapper.
    window = _window("same element", before=300, after=300)
    for token in ("dark", "white", "event"):
        assert token in window, f"same-element rule does not name {token!r}: {window!r}"
    assert re.search(r"paint|fill|background", window), (
        f"same-element rule does not say it is the element that paints: {window!r}"
    )


def test_prompt_still_forbids_style_elements():
    # Already true at HEAD (HTML RULES); pinned so the rewrite cannot drop it.
    assert re.search(r"(do not|don't|never)[^.]{0,20}emit a <style> element", PLAIN)


# --- Empty section_html: improvise with design-system class tokens -----------

EMPTY_CONDITION = (
    r"(section_html (is |was )?(empty|missing|blank|absent|null|not provided)"
    r"|(empty|missing|blank|absent) section_html)"
)

EMPTY_RULES = (
    ("condition: section_html empty", EMPTY_CONDITION),
    (
        "improvise from purpose / content_brief / resolved_style",
        EMPTY_CONDITION + r".{0,500}(improvise|invent|design|compose|create)[^.]{0,200}"
        r"(purpose|content_brief|resolved_style)",
    ),
    (
        "resolved_style is the improvisation source",
        EMPTY_CONDITION + r".{0,700}resolved_style",
    ),
    (
        "paint with design-system class tokens when design_system_active is true",
        EMPTY_CONDITION + r".{0,900}design_system_active.{0,200}"
        r"(design[- ]system )?class tokens?",
    ),
    (
        "inline color/background permitted when design_system_active is false",
        r"design_system_active is false.{0,300}inline.{0,80}(color|background)"
        r".{0,80}permit",
    ),
    (
        "never a bare .slide that relies on section { background }",
        r"(do not|don't|never)[^.]{0,80}(emit|output|produce|rely|return)[^.]{0,120}"
        r"(bare|plain|unclassed|unstyled)[^<]{0,40}(slide|<div class=.slide.>)"
        r".{0,240}section\s*\{\s*background",
    ),
)


@pytest.mark.parametrize(("description", "pattern"), EMPTY_RULES, ids=[d for d, _ in EMPTY_RULES])
def test_prompt_states_empty_section_html_rule(description, pattern):
    assert re.search(pattern, PLAIN), f"builder prompt lacks: {description}"


@pytest.mark.parametrize("selector", (".slide", ".slide.dark", ".slide.white", ".slide.event"))
def test_empty_rule_names_the_design_system_selectors(selector):
    match = re.search(EMPTY_CONDITION, PLAIN)
    assert match, "prompt has no empty-section_html rule"
    window = PLAIN[match.start() : match.start() + 1200]
    # `.slide` is a prefix of the others; require the exact selector as its own token.
    assert re.search(rf"(?<![\w.]){re.escape(selector)}(?![\w-])", window), (
        f"empty-section_html rule does not name {selector!r}"
    )


# --- OUTPUT: html may be a <section> wrapping div.slide ----------------------


def test_output_html_may_be_a_section_wrapping_div_slide():
    output = _block("OUTPUT")
    assert re.search(
        r"<section>[^.]{0,80}(wrap|contain|around)[^.]{0,60}(div\.slide|div class=.slide.)|"
        r"(wrapping|wrapped|wraps) (a |an |the )?(div\.slide|<div class=.slide.>)",
        output,
    ), f"OUTPUT does not say html may be a <section> wrapping div.slide: {output!r}"


# Negative: the fragment's outer root must not be required to be exactly <div class="slide">.
EXACT_DIV_ROOT_REQUIREMENTS = (
    # the pre-Task-6 sentence, verbatim shape
    r"\(an? <div class=.slide.> element\)",
    r"html fragment[^.]{0,20}\(?an? <div class=.slide.>( element)?\)?",
    r"(must|should|always|exactly|only)[^.]{0,60}(start|begin|open|root|wrap)[^.]{0,60}"
    r"<div class=.slide.>",
    r"outer root[^.]{0,60}(must be|is|exactly|always)[^.]{0,30}<div class=.slide.>",
    r"(root|outer) (tag|element) (must|should) be (a |an |the )?<div",
)


@pytest.mark.parametrize("pattern", EXACT_DIV_ROOT_REQUIREMENTS)
def test_prompt_does_not_require_outer_root_to_be_div_slide(pattern):
    # Anchor first so this cannot pass vacuously on a prompt that never mentions <section>.
    assert "<section>" in _block("OUTPUT"), "OUTPUT block must mention <section> as a legal root"
    assert not re.search(pattern, PLAIN), (
        f'prompt still requires the outer root to be exactly <div class="slide">: /{pattern}/'
    )


# --- The promoted manifest carries the same prompt ---------------------------


def test_manifest_builder_prompt_is_the_skill_instructions():
    # Green until the prompt is edited; red between the edit and `evals.harness.promote`.
    manifest = load_graph_v1_manifest()
    builder = next(d for d in manifest.definitions if d.agent_key == "builder")
    assert builder.prompt_text == INSTRUCTIONS
